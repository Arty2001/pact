"""
Generate the robot's spoken test cues and emit them as a C header.

The robot reads the test script aloud rather than the human following a
written table, which removes the thing that ruined the first attempt: the
recording window and the person doing the actions were never in sync. Now
the device drives the schedule and prints a marker on the same clock as the
frames, so every cue is timestamped against the footage exactly.

Speech is synthesised here with Windows SAPI and baked into the firmware as
8-bit PCM. No TTS runs on the device - these are seven fixed phrases, and a
lookup table is the right size of solution.

    python make_voice.py
"""

import os
import struct
import subprocess
import sys
import tempfile
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "voice.h")

RATE = 16000

# (symbol, spoken text, how long the step should last)
LINES = [
    ("READY",   "Pact tracking test. Please step out of view.",      6),
    ("STILL",   "Stand still in front of me.",                      20),
    ("LEFT",    "Now walk slowly to your left, then stop.",         20),
    ("RIGHT",   "Now walk slowly to your right, then stop.",        20),
    ("SIT",     "Sit down, and stay still.",                        20),
    ("WAVE",    "Stand up and wave your arm.",                      20),
    ("LEAVE",   "Now walk out of the room.",                        20),
    ("DONE",    "All done. Thank you.",                              4),
]

# Lines the tracker itself uses, outside the scripted test. Separate list
# because these are triggered by what the robot sees, not by a schedule.
CUES = [
    ("HELLO",  "I can see you."),
    ("PROMPT", "Stand in front of me, and walk slowly to your left, "
               "then to your right."),
    ("LOST",   "I have lost you."),
]


def synth(text, path):
    """Windows SAPI to a 16 kHz mono WAV."""
    ps = (
        "Add-Type -AssemblyName System.Speech; "
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer; "
        "$s.Rate = -1; "
        "$f = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo("
        f"{RATE}, "
        "[System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen, "
        "[System.Speech.AudioFormat.AudioChannel]::Mono); "
        f"$s.SetOutputToWaveFile('{path}', $f); "
        f"$s.Speak('{text}'); "
        "$s.SetOutputToNull(); $s.Dispose()"
    )
    subprocess.run(["powershell", "-NoProfile", "-Command", ps],
                   check=True, capture_output=True)


def to_u8(path):
    """16-bit signed WAV -> 8-bit unsigned PCM, peak-normalised.

    8-bit halves the flash cost and is plainly good enough for a spoken cue;
    normalising matters more than depth here, because a quiet phrase through
    a small speaker is the difference between a usable cue and one the
    person misses while walking away from the robot.
    """
    with wave.open(path, "rb") as w:
        assert w.getsampwidth() == 2 and w.getnchannels() == 1, "unexpected wav"
        raw = w.readframes(w.getnframes())
    s16 = struct.unpack(f"<{len(raw) // 2}h", raw)
    peak = max(1, max(abs(v) for v in s16))
    gain = 32000 / peak
    return bytes(
        max(0, min(255, int(v * gain / 256) + 128)) for v in s16
    )


def main():
    chunks = []
    tmp = tempfile.mkdtemp()
    for sym, text, hold in LINES:
        wav = os.path.join(tmp, f"{sym}.wav")
        synth(text, wav)
        pcm = to_u8(wav)
        chunks.append((sym, text, hold, pcm))
        print(f"  {sym:<6} {len(pcm) / RATE:5.2f}s  {len(pcm) / 1024:6.1f} KB  {text}")

    extra = []
    for sym, text in CUES:
        wav = os.path.join(tmp, f"{sym}.wav")
        synth(text, wav)
        pcm = to_u8(wav)
        extra.append((sym, text, 0, pcm))
        print(f"  {sym:<6} {len(pcm) / RATE:5.2f}s  {len(pcm) / 1024:6.1f} KB  {text}")

    total = sum(len(c[3]) for c in chunks + extra)
    print(f"\ntotal {total / 1024:.1f} KB")

    with open(OUT, "w", newline="\n") as f:
        f.write("/* ========================================================"
                "===================\n"
                "   Spoken test cues, generated by host/make_voice.py.\n\n"
                "   The robot reads the test script aloud so the person and "
                "the recording\n"
                "   stay in step - the first attempt failed because they were "
                "not, and the\n"
                "   footage came back empty. Each cue prints a marker on the "
                "same clock as\n"
                "   the frames, so every step is timestamped against the "
                "footage.\n\n"
                "   8-bit unsigned PCM at 16 kHz, peak-normalised. Do not edit "
                "by hand.\n"
                "   ========================================================"
                "=================== */\n"
                "#pragma once\n\n#include <stdint.h>\n\n"
                f"#define VOICE_RATE {RATE}\n\n")

        for sym, text, hold, pcm in chunks + extra:
            f.write(f"/* \"{text}\" */\n")
            f.write(f"static const uint8_t kVoice{sym}[] = {{\n")
            for i in range(0, len(pcm), 20):
                f.write("    " + ",".join(str(b) for b in pcm[i:i + 20]) + ",\n")
            f.write("};\n\n")

        f.write("typedef struct {\n"
                "    const char    *text;   /* what it says, for the log */\n"
                "    const uint8_t *pcm;\n"
                "    uint32_t       len;\n"
                "    uint32_t       hold_s; /* how long the step lasts */\n"
                "} voice_cue_t;\n\n"
                "static const voice_cue_t kVoiceScript[] = {\n")
        for sym, text, hold, pcm in chunks:
            f.write(f'    {{ "{text}", kVoice{sym}, '
                    f"sizeof(kVoice{sym}), {hold} }},\n")
        f.write("};\n\n#define VOICE_STEPS "
                "((int)(sizeof(kVoiceScript) / sizeof(kVoiceScript[0])))\n")

    print(f"wrote {os.path.abspath(OUT)}")


if __name__ == "__main__":
    sys.exit(main())
